import React from 'react';
import timing from './timing.json';
import E from './events.json';
import {StoryFrame,Grade,dipAround} from '../../kit/series/StoryFrame';
import {TitleCard} from '../../kit/series/TitleCard';
import {Timing} from '../../kit/series/Captions';
import {Scent,Supplier,Recruit,Evidence,LockedShop,Street,Washing} from './scenes/Investigation';
import {Confrontation} from './scenes/Confrontation';
export const META={id:'Rabenfels02',durationSec:E.duration,audio:'episodes/rabenfels-02/mix.wav'};
const sceneAt=(t:number)=>{
 if(t<E.memory)return <Scent t={t}/>;
 if(t<E.recruit)return <Supplier t={t}/>;
 if(t<E.evidence)return <Recruit t={t}/>;
 if(t<E.door)return <Evidence t={t}/>;
 if(t<E.street)return <LockedShop t={t}/>;
 if(t<E.coat)return <Street t={t}/>;
 if(t<E.stairs)return <Washing t={t}/>;
 if(t<E.cut)return <Confrontation t={t}/>;
 return <TitleCard t={t} t0={E.cut} title="Rabenfels" subtitle="PART II · CLOVES"/>;
};
const gradeAt=(t:number):Grade=>t>=E.cut?'none':t>=E.memory&&t<E.recruit?'warm':'cold';
const dipAt=(t:number)=>dipAround(t,E.memory,.09)+dipAround(t,E.recruit,.11);
export const Episode:React.FC=()=> <StoryFrame sceneAt={sceneAt} gradeAt={gradeAt} dipAt={dipAt} timing={timing as Timing} redWords={['Cloves.','empty.','secret.','Safwan']} audio={META.audio}/>;
